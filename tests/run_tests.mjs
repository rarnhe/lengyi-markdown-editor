// Run with: node tests/run_tests.mjs. No npm or third-party modules required.
import { readFileSync, writeFileSync, mkdtempSync, rmSync, appendFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';

const html = readFileSync('markdown-editor.html', 'utf8');
const blocks = [...html.matchAll(/<script(?![^>]*\bsrc\s*=)[^>]*>([\s\S]*?)<\/script>/gi)].map(m => m[1]);
const tmp = mkdtempSync(join(tmpdir(), 'md-editor-js-'));
const checks = [];
function check(name, args) {
  const result = spawnSync(process.execPath, args, { encoding: 'utf8' });
  checks.push({ name, command: 'node ' + args.map(a => a.startsWith(tmp) ? '<inline-script>' : a).join(' '),
    ok: result.status === 0, output: ((result.stdout || '') + (result.stderr || '')).trim().slice(-12000) });
  process.stdout.write('\n=== ' + name + ' ===\n' + (result.stdout || '') + (result.stderr || ''));
}
try {
  check('i18n.js syntax', ['--check', 'i18n.js']);
  if (!blocks.length) {
    checks.push({ name: 'Inline JavaScript syntax', command: 'node --check <inline-script>', ok: false, output: 'No inline script found' });
  } else {
    blocks.forEach((code, i) => {
      const file = join(tmp, 'inline-' + i + '.js');
      writeFileSync(file, code, 'utf8');
      check('Inline JavaScript syntax #' + (i + 1), ['--check', file]);
    });
  }
  check('Extension background syntax', ['--check', 'extension/background.js']);
  check('Extension content bridge syntax', ['--check', 'extension/editor-bridge.js']);
  check('Extension popup diagnostics syntax', ['--check', 'extension/popup.js']);
  check('Extension runtime + isolation tests', ['--test', 'tests/test_extension.mjs']);
  check('Regression tests', ['--test', 'tests/test_editor.mjs']);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}

const generated = new Date().toISOString();
const rows = checks.map(c => '| ' + c.name + ' | ' + (c.ok ? 'PASS' : 'FAIL') + ' | `' + c.command + '` |').join('\n');
const report = [
  '# JavaScript Test Report',
  '',
  '> Auto-generated by `node tests/run_tests.mjs`. Run this in the repository root for Codex; the same command runs in GitHub Actions.',
  '',
  '- Generated (UTC): ' + generated,
  '- Commit: ' + (process.env.GITHUB_SHA || 'local working tree'),
  '- Result: **' + (checks.every(c => c.ok) ? 'PASS' : 'FAIL') + '**',
  '- Dependencies: **Node.js built-ins only; no npm install**',
  '',
  '| Check | Result | Command |', '|---|---|---|', rows, '',
  '## Diagnostic output',
  '',
  ...checks.map(c => '<details><summary>' + c.name + '</summary>\n\n```text\n' + (c.output || '(no output)') + '\n```\n</details>\n')
].join('\n');
writeFileSync('test_report.md', report + '\n', 'utf8');
if (process.env.GITHUB_STEP_SUMMARY) appendFileSync(process.env.GITHUB_STEP_SUMMARY, report + '\n');
console.log('\n' + report);
if (checks.some(c => !c.ok)) process.exitCode = 1;
